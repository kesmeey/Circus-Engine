"""Bind the reviewed PC presentation code to Android Canvas, without duplicating VM/UI logic."""
import hashlib
import json
from pathlib import Path
try:
    from .build_paths import build_root
except ImportError:
    from build_paths import build_root

ROOT = Path(__file__).resolve().parent.parent
SHARED = ['DesktopNativeFiles', 'DesktopEngine', 'DesktopSave', 'DesktopCaptures', 'DesktopImageCache', 'DesktopImageCacheAudit', 'DesktopLegacy', 'DesktopDd', 'Dc3FamilyAudit', 'WyResourcePathAudit', 'Dc3ProgressGalleryAudit', 'DesktopUnity', 'Dc3rNativeSlot', 'DesktopTransitionMask', 'TransitionMaskTests', 'LegacyInputAudit', 'DmOverlayAudit', 'DdTransitionAudit', 'DdPetalAudit', 'DdGalleryAudit', 'Dc2PcAudioMemoryAudit', 'PcChoiceAudit', 'LegacyChoiceStyleAudit', 'UnityMenuPerformanceAudit', 'Json']


def generate(build_dir=None):
    generated_build = build_root(build_dir)
    output = generated_build/'android'
    target = output/'shared/org/circus/core'
    if not target.resolve().is_relative_to(generated_build):
        raise ValueError('Android shared output escapes the selected build directory')
    target.mkdir(parents=True, exist_ok=True)
    manifest = {}
    for name in SHARED:
        source = ROOT/f'runtime/desktop/src/org/circus/core/{name}.java'
        original = source.read_text(encoding='utf-8')
        mapped = original.replace('import javax.sound.sampled.*;', '').replace('import javax.swing.*;', '')
        for old, new in [('java.awt.image.BufferedImage', 'org.circus.graphics.BufferedImage'),
                         ('java.awt.geom.AffineTransform', 'org.circus.graphics.AffineTransform'),
                         ('java.awt.event.*', 'org.circus.graphics.KeyEvent'),
                         ('java.awt.*', 'org.circus.graphics.*'),
                         ('javax.imageio.ImageIO', 'org.circus.graphics.ImageIO')]:
            mapped = mapped.replace(old, new)
        if 'java.awt' in mapped or 'javax.swing' in mapped or 'javax.imageio' in mapped:
            raise ValueError(f'Unmapped desktop dependency in {name}')
        (target/(name+'.java')).write_text('// Generated by generate_android_backend.py; edit the shared source.\n'+mapped, encoding='utf-8')
        manifest[name] = {'source': source.relative_to(ROOT).as_posix(), 'sha256': hashlib.sha256(source.read_bytes()).hexdigest()}
    (output/'shared-backend.json').write_text(json.dumps(manifest, indent=2)+'\n', encoding='utf-8')
    # Only this invocation's selected inputs participate in javac. A removed
    # SHARED entry must not return via an older generated .java file.
    return sorted(target/(name+'.java') for name in SHARED)


if __name__ == '__main__':
    import argparse
    cli=argparse.ArgumentParser(description=__doc__)
    cli.add_argument('--build-root',type=Path,help='Generated output root; defaults to CIRCUS_BUILD_ROOT or workspace build')
    args=cli.parse_args()
    generate(args.build_root)
