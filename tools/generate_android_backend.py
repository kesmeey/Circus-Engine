"""Bind the reviewed PC presentation code to Android Canvas, without duplicating VM/UI logic."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHARED = ['DesktopEngine', 'DesktopSave', 'DesktopCaptures', 'DesktopLegacy', 'DesktopDd', 'LegacyInputAudit', 'DmOverlayAudit']


def generate():
    target = ROOT/'build/android/shared/org/circus/core'
    target.mkdir(parents=True, exist_ok=True)
    manifest = {}
    for name in SHARED:
        source = ROOT/f'runtime/desktop/src/org/circus/core/{name}.java'
        original = source.read_text(encoding='utf-8')
        mapped = original.replace('import javax.sound.sampled.*;', '').replace('import javax.swing.*;', '')
        for old, new in [('java.awt.image.BufferedImage', 'org.circus.graphics.BufferedImage'),
                         ('java.awt.geom.AffineTransform', 'org.circus.graphics.AffineTransform'),
                         ('java.awt.event.*', 'org.circus.graphics.KeyEvent'),
                         ('java.awt.*', 'org.circus.graphics.*'),
                         ('javax.imageio.ImageIO', 'org.circus.graphics.ImageIO')]:
            mapped = mapped.replace(old, new)
        if 'java.awt' in mapped or 'javax.swing' in mapped or 'javax.imageio' in mapped:
            raise ValueError(f'Unmapped desktop dependency in {name}')
        (target/(name+'.java')).write_text('// Generated by generate_android_backend.py; edit the shared source.\n'+mapped, encoding='utf-8')
        manifest[name] = {'source': source.relative_to(ROOT).as_posix(), 'sha256': hashlib.sha256(source.read_bytes()).hexdigest()}
    (ROOT/'build/android/shared-backend.json').write_text(json.dumps(manifest, indent=2)+'\n', encoding='utf-8')
    return sorted(target.glob('*.java'))


if __name__ == '__main__':
    generate()
